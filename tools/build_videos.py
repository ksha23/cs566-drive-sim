"""Write the video cards of index.html (section 5) from assets/videos/index.json, so the page needs no script and
also works when opened from a local copy. Run after changing the video list: python3 tools/build_videos.py"""
import html
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
START, END = "<!-- video cards: generated by tools/build_videos.py -->", "<!-- end of video cards -->"


def card(v):
    e = lambda s: html.escape("" if s is None else str(s))
    gt = v.get("real_ground_truth")
    gt = (" · real ground truth" if gt is True else " · no real frame (visual check)" if gt is False
          else f" · ground truth: {e(gt)}" if gt else "")
    shown = f'<p class="meta">Panels: {e(v["shown"])}</p>' if v.get("shown") else ""
    return (f'<div class="card"><video controls muted playsinline preload="metadata" src="{e(v["file"])}"></video>'
            f'<h3>{e(v["title"])}</h3><p class="meta">{e(v["scenario"])} · {e(v["dataset"])}{gt}</p>{shown}'
            f'<p>{e(v["caption"])}</p><p class="meta">{e(v["attribution"])}</p></div>')


def main():
    videos = json.load(open(os.path.join(ROOT, "assets/videos/index.json")))
    p = os.path.join(ROOT, "index.html"); s = open(p).read()
    a, b = s.index(START) + len(START), s.index(END)
    s = s[:a] + "\n" + "\n".join("      " + card(v) for v in videos) + "\n      " + s[b:]
    open(p, "w").write(s)
    print(f"{len(videos)} video cards written")


if __name__ == "__main__":
    main()
